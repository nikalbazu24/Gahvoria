"""Share the pinned, typed ability glossary with the offline Java sentence adapter.

Reads our generated Ruby asset, not game files. Run after build_pokemon_glossary.py.
"""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
asset = (root / 'engine/src/main/assets/essentia_preload/essentia_pokemon_terms.rb').read_text(encoding='utf-8')
section = asset.split('    :ability => {', 1)[1].split('    },', 1)[0]
pairs = []
for a, b in re.findall(r'^      (".*") => (".*"),$', section, re.M):
    pairs.append((json.loads(a), json.loads(b)))
assert len(pairs) > 300
lines = [
    'package com.hatkid.mkxpz.translate;', '',
    '// Generated by tools/build_neural_lexicon.py from the pinned PokéAPI ability names.',
    '// BSD-3-Clause attribution: engine/src/main/assets/licenses/pokeapi.txt.',
    '// Only matched as a possessed noun, never as a global word replacement.',
    'final class NeuralTerms {',
    '    static final String[][] ABILITIES = {'
]
for a, b in sorted(pairs, key=lambda p: (-len(p[0]), p[0])):
    lines.append('        {' + json.dumps(a, ensure_ascii=False) + ', ' + json.dumps(b, ensure_ascii=False) + '},')
lines += ['    };', '    private NeuralTerms() {}', '}', '']
(root / 'engine/src/main/java/com/hatkid/mkxpz/translate/NeuralTerms.java').write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(pairs)} scoped ability names shared with Neural')
