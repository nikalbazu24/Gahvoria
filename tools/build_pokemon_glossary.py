"""Rebuild the offline, typed EN→ES glossary from a pinned PokéAPI checkout.

Usage: python3 tools/build_pokemon_glossary.py /path/to/pokeapi
Only names are copied; no game scripts or descriptions. Runtime never downloads data.
"""
import csv
import json
from pathlib import Path
import subprocess
import sys

REVISION = '8a92bfa7dab2f12b84b5d151562f9857c133ff30'
source = Path(sys.argv[1]).resolve()
if subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip() != REVISION:
    raise SystemExit('Unexpected PokéAPI revision')
root = Path(__file__).resolve().parents[1]
tables = {'move': 'move', 'item': 'item', 'ability': 'ability', 'type': 'type', 'nature': 'nature'}
lines = ['# encoding: UTF-8', '# Generated by tools/build_pokemon_glossary.py. Do not edit by hand.',
         '# PokéAPI BSD-3-Clause; see licenses/pokeapi.txt. Names only, scoped by category.',
         'module GahvoriaPokemonTerms', '  REVISION = ' + repr(REVISION), '  NAMES = {']
counts = {}
for kind, table in tables.items():
    rows = list(csv.DictReader((source / f'data/v2/csv/{table}_names.csv').open(encoding='utf-8')))
    en = {r[f'{table}_id']: r['name'] for r in rows if r['local_language_id'] == '9'}
    es = {r[f'{table}_id']: r['name'] for r in rows if r['local_language_id'] == '7'}
    terms = {}
    ambiguous = set()
    for key in en.keys() & es.keys():
        if en[key] in terms and terms[en[key]] != es[key]: ambiguous.add(en[key])
        terms[en[key]] = es[key]
    for term in ambiguous: del terms[term]
    counts[kind] = len(terms)
    lines.append(f'    :{kind} => {{')
    for a,b in sorted(terms.items()):
        # JSON double-quoted strings have no Ruby interpolation in this data.
        assert '#{' not in a+b and '#@' not in a+b and '#$' not in a+b
        lines.append('      ' + json.dumps(a, ensure_ascii=False) + ' => ' + json.dumps(b, ensure_ascii=False) + ',')
    lines.append('    },')
lines += ['  }', 'end', '']
(root / 'engine/src/main/assets/essentia_preload/essentia_pokemon_terms.rb').write_text('\n'.join(lines),encoding='utf-8')
license = subprocess.check_output(['git','-C',str(source),'show','HEAD:LICENSE.md'], text=True)
(root / 'engine/src/main/assets/licenses/pokeapi.txt').write_text(license,encoding='utf-8')
print(counts, 'total:',sum(counts.values()))
